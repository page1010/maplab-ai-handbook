#    婚禮 candy bar 正是主打,企業場的熱食也照常供應,全擋等於把主力生意也封掉。
OFFSCOPE='敬酒|換裝|每個時段|各時段|分時段|逐時段|時段的餐點|公益酒會|慈善酒會'
#    假設客人準備好的道具(同一則訊息:「抓周的道具就好,紅布太具體也不見得每家都準備」):
#    道具可以寫,但不能指定哪一件。客人家裡沒有那件東西,整句話就跟他無關。
ASSUMEPROP='紅布'

fail=0
n=0
opens=""
while IFS= read -r line; do
  case "$line" in ""|\#*) continue;; esac
  n=$((n + 1))
  msgs=""

  hit=$(printf '%s' "$line" | grep -oE "$PROCESS" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [工作內容敘述] 命中:$hit"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$INTERNAL" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [內部文件術語] 命中:$hit"
  fi

  # 服務範圍例外(Owner msg 2026-09-30T17:43:55 回 Q4,原話「q4做得到」):
  # 「導航/車程 30 分鐘內的地點不另計交通費」講的是服務範圍與收費,不是回覆速度,
  # 而且 Owner 親口確認做得到。第 ⑤ 類擋的是「多久內一定會回你」這種會跳票在客人身上的承諾,
  # 範圍描述不在它的射程內——先把這段挖掉再比對,其餘的分鐘內照擋。
  slaline=$(printf '%s' "$line" | sed -E 's/(導航|車程|路程)[^,。]*分鐘內//g')
  hit=$(printf '%s' "$slaline" | grep -oE "$SLA" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [做不到的承諾] 命中:$hit ——回覆速度與到貨時間會因為當機或額度用完跳票,不寫死"
  fi

  # 第 ⑥ 類只在 ad 設定檔生效:它管的是「文案結尾把人叫去留言、按鈕卻把人帶去網頁」,
  # 前提是有一顆廣告按鈕。文章沒有那顆按鈕,請讀者加 LINE 是正常的內文收尾,不該擋。
  if [ "$PROFILE" = "ad" ]; then
    hit=$(printf '%s' "$line" | grep -oE "$CTAMIX" | sort -u | tr '\n' ' ')
    if [ -n "$hit" ]; then
      msgs="$msgs
    [按鈕與文案打架] 命中:$hit ——按鈕是「了解更多」會把人帶到網頁,文案不要把人叫回留言區"
    fi
  fi

  hit=$(printf '%s' "$line" | grep -oE "$BRAND" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [品牌禁用語] 命中:$hit ——品牌用語手冊第 57 行禁用字詞"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$OPSNUM" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [營運門檻外露] 命中:$hit ——低消與起訂門檻不對外寫,同業照著開就好;改成請對方來問"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$LACK" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [匱乏敘事] 命中:$hit ——在講客人缺什麼、多可憐,改成講我們接手了哪一塊"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$HANDOFF" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [把工作丟回客人] 命中:$hit ——動作主體寫成客人要交出來,改成「交給我們／我們接手／我們負責」"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$JOBTITLE" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [指名職務] 命中:$hit ——在企業裡是位階標籤,不點名也講得通,用「你」或不指名的寫法"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$ASSIGN" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [把工作派給客人] 命中:$hit ——廣告裡不分配工作給看的人,改成寫他因此能從容做什麼"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$DOWNPLAY" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [把餐飲寫成多餘] 命中:$hit ——餐飲是收錢的東西,不是要被壓小的干擾項;改成寫這份餐飲打開了什麼"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$OFFSCOPE" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [寫了不主打的場景] 命中:$hit ——這不是我們在接的生意,寫了來詢問的人期待會對不上;對照 docs/ADS_SERVICE_SCOPE.md"
  fi

  # 熱食不全擋:企業場的熱食照常供應。只有跟婚禮/草地/戶外同時出現才是錯的,
