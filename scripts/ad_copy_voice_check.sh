  fi
  if [ "$person" -eq 0 ]; then
    msgs="$msgs
    [沒有主體] 全篇沒有任何指向人的詞"
  fi

  if [ -n "$msgs" ]; then
    fail=$((fail + 1))
    echo "FAIL 第 $n 則:$line$msgs"
  fi
