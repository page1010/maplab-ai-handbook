  if printf '%s' "$line" | grep -qE '婚宴' && printf '%s' "$line" | grep -qE '出餐|正餐|上菜|桌菜|宴席'; then
    msgs="$msgs
    [寫了不主打的場景] 婚宴正餐 ——我們的位置是賓客入席前的甜點桌與婚禮前排練的點心,不是宴席本身"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$ASSUMEPROP" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [假設客人有的道具] 命中:$hit ——不見得每家都準備,客人沒有那件東西整句就跟他無關;寫不指定的講法"
  fi

  person=$(printf '%s' "$line" | grep -coE "$PERSON" || true)
  props=$(printf '%s' "$line" | grep -oE "$PROP" | sort -u | wc -l | tr -d ' ')
