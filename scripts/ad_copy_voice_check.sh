#!/bin/bash
# ad_copy_voice_check.sh — 廣告文案「有沒有對客人說話」的機器檢查
#
# 由來:Owner msg 2026-09-30T15:33:34「你文案在敘述場景在敘述你的工作內容,
#       就沒有對我客人好好說話」。前一輪只跑了禁語表掃描就宣稱文案沒問題,
#       禁語表管的是「有沒有講不該講的話」,管不到「有沒有對人說話」——
#       缺了這道檢查,十則裡有十則的主詞都不是客人。
#
# 定位:這是缺陷棘輪(企業文化原則 2)的閘門腳本層,不是清單層。
#       執行層零 LLM,純樣式比對,結果可重現。
#
# 用法:bash scripts/ad_copy_voice_check.sh <文案檔> [ad|article]
#       檔案格式:一行一則文案,空行與 # 開頭的行略過。第二參數省略時視為 ad。
# 回傳:全過 exit 0;有任何一則命中 exit 1。
#
# 兩套設定檔的由來(Owner msg 6388,2026-09-30T17:58:55):
#   原話:「品牌用語在文章,廣告是cta,不打架,什麼時候做什麼事」。
#   9/30 稍早這支腳本把 skills/brand-voice-guide.md 第 57 行整條原封不動搬進來,
#   那份手冊是寫給文章用的,等於拿文章的尺去量廣告——所以才會出現一句正常的 CTA
#   被自家閘門判違規。打架的不是兩套規則,是一套規則被用在兩個地方。
#   文章負責讓人願意相信,廣告只負責把對的人帶到頁面上,兩邊該擋的本來就不一樣。
#   差別只有兩處,其餘七類兩邊完全相同(見下方 BRAND 與第 ⑥ 類)。
#   這是 Owner 重述意圖後的閘門修訂,不是為了讓自己的稿過關而放寬(企業文化原則 12 第 5 條)。
set -u

FILE="${1:-}"
PROFILE="${2:-ad}"
if [ -z "$FILE" ] || [ ! -f "$FILE" ]; then
  echo "用法:bash scripts/ad_copy_voice_check.sh <文案檔> [ad|article]"
  exit 2
fi
case "$PROFILE" in
  ad|article) ;;
  *) echo "第二參數只能是 ad 或 article,收到:$PROFILE"; exit 2;;
esac

# ① 自家工作流程術語:在講內部怎麼做事,不是在講客人得到什麼
PROCESS='一手規劃|一次交辦|一次到位|一次規劃|一站式|全方位|專業團隊|量身打造|客製化|流程|方案規劃|統籌'

# ② 內部製作文件術語:分鏡表、拍攝腳本誤植進廣告欄位
INTERNAL='前[0-9]+秒|尾板|分鏡|近拍|全景|開場→|→整桌|B-?roll|版位|素材'

# ③ 指向人的詞:一則文案裡完全沒有這類詞,代表整則沒有主體
#    2026-09-30T17:28:51 修訂(Owner 原話:「先思考 你在對誰說話 ta是誰。
#    一定是假設他們是潛在客戶有需求」)——原表漏了第二人稱。企業文化原則 12 寫的是
#    「對外文字的主詞必須是看的人」,而「你／妳／您」正是最直接的那個主詞;
#    漏掉它會讓 Owner 自己給的示例(「你也在找這樣的會議點心嗎」)被自家閘門判無主體。
#    這是補漏不是放寬,配套把第 ④ 類改成獨立判定,見下。
#    2026-09-30T22:28:35 修訂(Owner msg 6429「也不要指名行政窗口。在企業中有貶低的意思」):
#    原表把「行政」「窗口」算成指向人的詞,等於鼓勵文案去點名那個職務。
#    兩個詞已移出本表並移進第 ⑪ 類擋掉,改寫時要靠「你／主辦／來的人」當主詞。
#    2026-10-01T09:12:42 修訂(Owner 本人改字時用了「貴賓」與「客戶」):
#    Owner 親手改的句子「你把時間留給議程與貴賓」「我們用點心,客戶用點心」被本表判無主體,
#    依 9/30 定下的回灌規則「Owner 的字被自家閘門判 FAIL 時改閘門不改字」補進本表。
#    貴賓/來賓/客戶/業主都是企業場的「看的人或他要招待的人」,與客人/賓客同一族。
PERSON='你|妳|您|媽媽|爸爸|家人|長輩|兒孫|孩子|寶寶|新人|賓客|來客|貴賓|來賓|客戶|業主|主人|同事|主辦|接待|講者|客人|大家|來的人'

# ④ 純佈景名詞:兩個以上同時出現 = 在描述桌子長什麼樣
#    2026-09-30T17:28:51 修訂:原本只在「整則沒有指向人的詞」時才判,
#    第 ③ 類納入第二人稱後,只要句尾加一個「你」就能繞過去——那等於自己開後門。
#    改成獨立判定:佈景名詞 2 個以上一律擋,有沒有人稱都一樣。這是收緊不是放寬。
PROP='桌巾|層架|金架|鮮花|色系|佈置|擺設|器皿|餐具|花藝'

# ⑤ 做不到的服務承諾(Owner msg 2026-09-30T15:47):
#    「30 分鐘 LINE 回覆」這種話說出去就是承諾。回覆這條線由模型與額度撐著,
#    當機、額度滿、人不在都會讓承諾跳票,而跳票的成本落在客人身上不是落在我們身上。
#    凡是把「多久內一定會怎樣」寫死的,一律擋。
SLA='[0-9]+ *分鐘內|[0-9]+ *小時內|半小時內|當天回覆|當日回覆|馬上回覆|立刻回覆|立即回覆|即時回覆|秒回|隨時回覆|24 *小時|全年無休|不打烊|使命必達|準時送達|保證|一定會|絕對|包您|包你|免費試吃'

# ⑥ 按鈕與文案打架(Owner msg 2026-09-30T16:02):
#    「了解更多」是引流到網頁的按鈕,十則廣告的 CTA 全部是它。
#    文案結尾卻在叫人留言或私訊,等於文字要對話、按鈕導連結,兩邊把人往不同地方推。
#    按鈕是 LEARN_MORE 時,結尾要請人去看頁面,不是請人留言。
CTAMIX='留言|私訊|傳訊|加 *LINE|加我們 *LINE|小盒子|inbox|DM'

# ⑦ 品牌用語手冊的禁用字詞(skills/brand-voice-guide.md 第 57 行),機器化:
#    手冊一直存在,但從來沒有東西在跑它,所以它管不到任何一則實際上架的文案。
#    Owner msg 2026-09-30T16:2x 明示可用「儘速預約檔期/快預約下一場派對/專屬你的質感開幕」,
#    那是對手冊「趕快預約」「質感」兩條的具名例外,已寫回手冊;例外之外的照擋。
#    2026-09-30T17:28:51 補入禁語表那五個詞:Owner msg 5961(2026-09-23)親口裁
#    「賓主盡歡不要」,`claude-daily-operations/state/dispatch/SEO_COPY_RUBRIC.md:35`
#    同時列了動線／琳瑯滿目／賓至如歸／賓客絡繹不絕。那份表是 SEO 稿的唯一真相,
#    但從來沒有任何東西在廣告這一側跑它——所以 9/23 裁掉的詞,廣告文案照樣寫得出來。
#    現在機器擋:Owner 要收回這一條,直接說,改的是這一行不是憑記憶。
#
#    2026-09-30T17:58:55 拆成兩段(Owner msg 6388「品牌用語在文章,廣告是cta」):
#    ・BRAND_COMMON=誇大不實與硬推。這一組在哪一側都不能寫,兩套設定檔共用。
#      「趕快預約」留在這裡,是因為那條是 Owner 在廣告這一側親口裁的,
#      不是從文章手冊搬過來的,不在這次拆分的射程內。
#    ・BRAND_ARTICLE_EXTRA=9/23 msg 5961 與 SEO_COPY_RUBRIC.md:35 裁掉的五個贅詞。
#      那份表的管轄範圍是 SEO 文章,所以只在 article 設定檔生效。
#      廣告那側不再由這五個詞管——廣告的工作是把對的人帶到頁面上,
#      會傷到客人的是第 ⑤ ⑥ ⑧ 類與沒有主體,不是這五個形容詞。
BRAND_COMMON='最頂|超值|保證滿意|CP值爆高|佛心|便宜又大碗|錯過可惜|趕快預約|名額有限|一生一次不能省|不訂會後悔|限時優惠'
BRAND_ARTICLE_EXTRA='賓主盡歡|賓至如歸|賓客絡繹不絕|琳瑯滿目|動線'
if [ "$PROFILE" = "article" ]; then
  BRAND="$BRAND_COMMON|$BRAND_ARTICLE_EXTRA"
else
  BRAND="$BRAND_COMMON"
fi

# ⑧ 營運門檻數字不對外(Owner msg 2026-09-30T17:43:55 回 Q1/Q2):
#    原話:「Q1是看低消 但不想暴露給同業 需要再來詢價」「q2 你也不需要拿這個做文章,
#    當然愈早愈好」。這一條比原則 12 第四條更前面一步——第四條講的是「不知道就不准編」,
#    這條講的是「知道了也不准寫」:接不接一場看的是低消不是人頭數,而低消一旦寫在
#    對外文字上,同業照著開就好。所以起訂人數、最低消費、提前天數三類數字,
#    不是留白等 Owner 補,是永久不對外露出,一律導去詢價。
#    Owner 16:17:16 同一天先講過一次:「你可以不要用一些你不知道的幾人起訂」。
OPSNUM='[0-9０-９]+ *人起|[0-9０-９]+ *人以上|[0-9０-９]+ *位以上|人起訂|起訂|最低消費|低消|最低訂購|[0-9０-９]+ *份起|[0-9０-９]+ *天前預訂|提前 *[0-9０-９]+ *天|[0-9０-９]+ *個工作天|滿 *[0-9０-９]+ *元'

# ⑨ 匱乏敘事(Owner msg 6427 2026-09-30T22:05:43 + msg 6428 22:16:35):
#    6427 原話:「要顧的不是 而是 你的文案滿滿地雷 改成你安心接待 餐點我來 這種口氣」。
#    6428 只丟了半句:「行政窗口常常是．．．」——那半句是本線自己寫的第 03 則廣告原文
#    「行政窗口常常是最後一個吃到東西的人」。同一個毛病被指第二次,所以升到機器層。
#    第 ③ 類查的是「有沒有對人說話」,主詞對了照樣可以寫成站在旁邊評論人家多可憐:
#    「最後一個吃到東西的人」「手幾乎沒空過」「本來就滿檔的那一週」「人手通常不夠」。
#    客人不需要被服務提供者提醒自己很累,更不需要被推測他在公司裡被丟了什麼爛事。
#    改法不是換形容詞,是改成講外燴接手了什麼範圍——「你安心接待,餐點我們來」。
#    注意:「不用／不必」不在這一類裡,那是講接手之後客人不必做什麼,方向是對的。
LACK='最後一個.{0,6}(吃|坐)|幾乎沒有|幾乎沒空|沒空過|沒空吃|沒有時間|沒時間|沒停過|沒吃幾口|沒吃上|沒機會|沒坐下|來不及|抽不出|忙到|人手.{0,3}不夠|忙著招呼|落在.{0,8}身上|本來就滿檔|滿檔的那一[週周天]|顧[^,。]{0,6}、顧'

# ⑩ 把工作丟回客人(Owner msg 6429 2026-09-30T22:28:35):
#    原話:「餐點先交出來  餐點交給我們」。
#    「餐點先交出來談」是站在我們這邊叫客人把東西吐出來——動作的主體是客人,
#    而且那個動作是他要多做一件事(交、丟、分出去),聽起來像在催他辦手續。
#    「餐點交給我們」是同一件事反過來寫:動作的主體是我們,客人什麼都不必做。
#    第 ⑨ 類擋的是「講客人缺什麼」,這一類擋的是「把工作講成客人要交出來的東西」。
#    改法:交出來 → 交給我們 / 我們接手 / 我們負責。
HANDOFF='交出來|交出去|先交出|交出|丟出來|丟出去|分出去|分出來|丟給我們|外包出去'

# ⑪ 指名職務(Owner msg 6429 同一則):
#    原話:「也不要指名行政窗口。在企業中有貶低的意思」。
#    「行政窗口」在企業裡是個位階標籤,把它寫在廣告上等於替看的人貼標籤——
#    而看的人正是我們要說服的那個人。同一句話不點名職務照樣講得通:
#    「行政窗口要顧報到」→「報到與場地你顧」。
#    射程只放 Owner 點名的這一族(行政／窗口)。主辦、接待、講者是場上的分工描述,
#    Owner 沒有裁,不自行擴張;要擴張就拿 Owner 原話來改這一行。
JOBTITLE='行政窗口|行政同事|行政人員|行政助理|行政小姐|負責的窗口|行政|窗口'

# ⑫ 把工作派給客人(Owner msg 2026-10-01T09:12:42):
#    原話:「所有 你顧 你盯 的用詞都很不恰當 語氣很奇怪,第一性原理,『講者與時間你盯』
#    要表達什麼?聽起來像是你把工作交給我們廣告TA」。
#    第 ⑩ 類擋的是「叫客人把東西交出來」,這一類擋的反向寫法:外燴把自己不做的那半
#    回頭指派給客人。「茶點交給我們,講者與時間你盯」在句構上是一張分工表,
#    而廣告看的人不是協力廠商,他是出錢的人——沒有人要在廣告裡被分配工作。
#    Owner 給的目的很明確:要寫那個人的從容與代入感,不是寫他的待辦清單,也不能寫他狼狽。
#    改法:把「你顧/你盯 X」換成那個人因為餐飲不必分心而真正能做的事
#    (「你和賓客一起享用餐點」「讓中場氣氛熱絡起來」),動詞要是享用、參與、交談、放心,
#    不是顧、盯、張羅。射程只放 Owner 點名的顧/盯兩字,不自行擴張到「負責」。
ASSIGN='[你妳][^,。、]{0,6}(顧|盯)'

fail=0
n=0
while IFS= read -r line; do
  case "$line" in ""|\#*) continue;; esac
  n=$((n + 1))
  msgs=""

  hit=$(printf '%s' "$line" | grep -oE "$PROCESS" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [工作內容敘述] 命中:$hit"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$INTERNAL" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [內部文件術語] 命中:$hit"
  fi

  # 服務範圍例外(Owner msg 2026-09-30T17:43:55 回 Q4,原話「q4做得到」):
  # 「導航/車程 30 分鐘內的地點不另計交通費」講的是服務範圍與收費,不是回覆速度,
  # 而且 Owner 親口確認做得到。第 ⑤ 類擋的是「多久內一定會回你」這種會跳票在客人身上的承諾,
  # 範圍描述不在它的射程內——先把這段挖掉再比對,其餘的分鐘內照擋。
  slaline=$(printf '%s' "$line" | sed -E 's/(導航|車程|路程)[^,。]*分鐘內//g')
  hit=$(printf '%s' "$slaline" | grep -oE "$SLA" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [做不到的承諾] 命中:$hit ——回覆速度與到貨時間會因為當機或額度用完跳票,不寫死"
  fi

  # 第 ⑥ 類只在 ad 設定檔生效:它管的是「文案結尾把人叫去留言、按鈕卻把人帶去網頁」,
  # 前提是有一顆廣告按鈕。文章沒有那顆按鈕,請讀者加 LINE 是正常的內文收尾,不該擋。
  if [ "$PROFILE" = "ad" ]; then
    hit=$(printf '%s' "$line" | grep -oE "$CTAMIX" | sort -u | tr '\n' ' ')
    if [ -n "$hit" ]; then
      msgs="$msgs
    [按鈕與文案打架] 命中:$hit ——按鈕是「了解更多」會把人帶到網頁,文案不要把人叫回留言區"
    fi
  fi

  hit=$(printf '%s' "$line" | grep -oE "$BRAND" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [品牌禁用語] 命中:$hit ——品牌用語手冊第 57 行禁用字詞"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$OPSNUM" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [營運門檻外露] 命中:$hit ——低消與起訂門檻不對外寫,同業照著開就好;改成請對方來問"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$LACK" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [匱乏敘事] 命中:$hit ——在講客人缺什麼、多可憐,改成講我們接手了哪一塊"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$HANDOFF" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [把工作丟回客人] 命中:$hit ——動作主體寫成客人要交出來,改成「交給我們／我們接手／我們負責」"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$JOBTITLE" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [指名職務] 命中:$hit ——在企業裡是位階標籤,不點名也講得通,用「你」或不指名的寫法"
  fi

  hit=$(printf '%s' "$line" | grep -oE "$ASSIGN" | sort -u | tr '\n' ' ')
  if [ -n "$hit" ]; then
    msgs="$msgs
    [把工作派給客人] 命中:$hit ——廣告裡不分配工作給看的人,改成寫他因此能從容做什麼"
  fi

  person=$(printf '%s' "$line" | grep -coE "$PERSON" || true)
  props=$(printf '%s' "$line" | grep -oE "$PROP" | sort -u | wc -l | tr -d ' ')
  if [ "$props" -ge 2 ]; then
    msgs="$msgs
    [場景敘述] 佈景名詞 $props 個 ——在描述桌子長什麼樣,句尾補一個人稱不算改好"
  fi
  if [ "$person" -eq 0 ]; then
    msgs="$msgs
    [沒有主體] 全篇沒有任何指向人的詞"
  fi

  if [ -n "$msgs" ]; then
    fail=$((fail + 1))
    echo "FAIL 第 $n 則:$line$msgs"
  fi
done < "$FILE"

echo "---"
if [ "$fail" -eq 0 ]; then
  echo "PASS:$n 則全部有對客人說話(設定檔 $PROFILE)"
  exit 0
fi
echo "FAIL:$n 則裡有 $fail 則不合格(設定檔 $PROFILE)"
echo "改法不是加形容詞,是把主詞換成客人,講那個人當天實際會遇到什麼事。"
echo "命中[做不到的承諾]的,改法是把承諾換成邀請,而邀請要跟按鈕同一個方向。"
echo "命中[按鈕與文案打架]的,改法是把結尾換成請人去看頁面,不是請人留言或私訊。"
echo "命中[匱乏敘事]的,改法是從「你缺了什麼」換成「我們接手了哪一塊」。"
echo "命中[把工作丟回客人]的,改法是「餐點先交出來」→「餐點交給我們」。"
echo "命中[指名職務]的,改法是不點名那個職務,主詞用「你」或改寫成分工描述。"
exit 1
